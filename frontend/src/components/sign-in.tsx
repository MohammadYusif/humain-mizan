import { LoaderCircle, LockKeyhole } from "lucide-react"
import { useId, useState, type FormEvent } from "react"

import { Wordmark } from "@/components/logo"
import { Alert, AlertDescription } from "@/components/ui/alert"
import { Button } from "@/components/ui/button"
import { Input } from "@/components/ui/input"
import { Label } from "@/components/ui/label"
import { api, errorMessage } from "@/lib/api"

/** The only screen someone without a session sees: the deployment is private, by invitation. */
export function SignIn({ onSignedIn }: { onSignedIn: (user: string) => void }) {
  const id = useId()
  const [username, setUsername] = useState("")
  const [password, setPassword] = useState("")
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const submit = async (e: FormEvent) => {
    e.preventDefault()
    if (!username.trim() || !password) return setError("Enter your user name and password.")
    setBusy(true)
    setError(null)
    try {
      const me = await api.login(username.trim(), password)
      onSignedIn(me.user ?? username.trim())
    } catch (err) {
      setError(errorMessage(err))
      setPassword("")
    } finally {
      setBusy(false)
    }
  }

  return (
    <div className="grid min-h-dvh bg-background lg:grid-cols-[minmax(0,1fr)_minmax(0,1.1fr)]">
      <section className="hidden flex-col justify-between border-e bg-paper p-12 lg:flex">
        <Wordmark size="lg" />
        <div className="flex max-w-md flex-col gap-4">
          <p className="font-heading text-3xl leading-tight font-semibold">
            Contract review that routes every contract: approve, negotiate or escalate.
          </p>
          <p className="text-[0.95rem] leading-relaxed text-muted-foreground">
            Arabic, English and bilingual contracts are checked clause by clause against your playbook. The route is
            computed by code, and anything risky goes to a lawyer.
          </p>
          <dl className="mt-2 grid grid-cols-[6.5rem_minmax(0,1fr)] gap-x-4 gap-y-2.5 border-t pt-5 text-sm">
            <dt className="font-semibold text-approve">Approve</dt>
            <dd className="text-muted-foreground">Meets the playbook. No one needs to touch it.</dd>
            <dt className="font-semibold text-negotiate">Negotiate</dt>
            <dd className="text-muted-foreground">The redline goes to the counterparty.</dd>
            <dt className="font-semibold text-escalate">Escalate</dt>
            <dd className="text-muted-foreground">A lawyer gets the contract with the exact question.</dd>
          </dl>
        </div>
        <p className="text-xs text-muted-foreground">Decision support generated by an AI agent; not legal advice.</p>
      </section>

      <section className="flex items-center justify-center px-4 py-12 sm:px-8">
        <div className="flex w-full max-w-sm flex-col gap-8">
          <Wordmark className="lg:hidden" />
          <div className="flex flex-col gap-2">
            <h1 className="text-2xl font-semibold">Sign in</h1>
            <p className="text-sm text-muted-foreground">
              This is a private preview for the HUMAIN Future AI Builders Hackathon. Access is by invitation.
            </p>
          </div>
          <form onSubmit={submit} className="flex flex-col gap-4" noValidate>
            <div className="flex flex-col gap-2">
              <Label htmlFor={`${id}-user`}>User name</Label>
              <Input
                id={`${id}-user`}
                autoComplete="username"
                autoCapitalize="none"
                spellCheck={false}
                value={username}
                onChange={(e) => setUsername(e.target.value)}
                className="h-10 bg-card"
                autoFocus
              />
            </div>
            <div className="flex flex-col gap-2">
              <Label htmlFor={`${id}-pw`}>Password</Label>
              <Input
                id={`${id}-pw`}
                type="password"
                autoComplete="current-password"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                className="h-10 bg-card"
              />
            </div>
            {error ? (
              <Alert className="border-escalate/40 bg-escalate-soft text-escalate" aria-live="polite">
                <AlertDescription className="text-foreground/85">{error}</AlertDescription>
              </Alert>
            ) : null}
            <Button type="submit" className="mt-1 h-10" disabled={busy}>
              {busy ? <LoaderCircle className="animate-spin" aria-hidden /> : <LockKeyhole aria-hidden />}
              {busy ? "Signing in…" : "Sign in"}
            </Button>
          </form>
          <p className="text-xs text-muted-foreground lg:hidden">
            Decision support generated by an AI agent; not legal advice.
          </p>
        </div>
      </section>
    </div>
  )
}
