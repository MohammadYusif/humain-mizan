"""PDF exports a legal team can file or send as they are, typeset with Typst (Apache-2.0).

- redline.pdf: the full contract; each offending quote is struck through and the playbook wording is
  proposed under the clause with the rule and the reason. Arabic is laid out right-to-left.
- memo.pdf: the decision memo: route and reasons, what happened next, the agent's memo, findings,
  deterministic red flags, and how the text was obtained (OCR confidence for scans).

Contract text is passed to the templates as JSON data, never as Typst markup, so a clause cannot
inject layout or code into the document.
"""

from __future__ import annotations

import json
import re
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .challenge import contracts as C
from .config import Settings

ASSETS = Path(__file__).parent / "assets"
FONTS = ASSETS / "fonts"
DISCLAIMER = (
    "Decision support generated by an AI agent (Mizan); not legal advice. Review before use."
)
ROUTE_LABEL = {"approve": "Approve", "negotiate": "Negotiate", "escalate": "Escalate"}
ROUTE_DESCRIPTION = {
    "approve": "Meets the playbook. Safe to sign without changes.",
    "negotiate": "Major deviations with playbook redlines. Send the redlines to the counterparty.",
    "escalate": "Critical risk or a gap the playbook cannot resolve. Needs a lawyer's decision.",
}
DECISION_LABEL = {
    "approve_contract": "Approved by legal",
    "request_changes": "Changes requested by legal",
    "reject": "Rejected by legal",
    "send": "Redline sent to the counterparty",
    "discard": "Draft discarded",
}
FLAG_TONE = {
    "critical": "critical",
    "unresolved": "major",
    "recorded": "minor",
    "cleared": "approve",
}


def _now() -> str:
    return datetime.now(UTC).strftime("%d %b %Y %H:%M UTC")


def _compile(template: str, data: dict[str, Any]) -> bytes:
    import typst

    files = {
        "main.typ": (ASSETS / template).read_bytes(),
        "base.typ": (ASSETS / "base.typ").read_bytes(),
        "logo.svg": (ASSETS / "logo.svg").read_bytes(),
        "data.json": json.dumps(data, ensure_ascii=False).encode("utf-8"),
    }
    return typst.compile(files, format="pdf", font_paths=[str(FONTS)], ignore_system_fonts=True)


def _span(clause_text: str, quote: str) -> tuple[int, int] | None:
    """Original-text span of a quote that was verified against the normalised clause."""
    norm, idx = C.normalize_with_map(clause_text)
    q = C.normalize(quote)
    at = norm.find(q) if q else -1
    if at < 0 or not idx:
        return None
    return idx[at], idx[at + len(q) - 1] + 1


def _segments(text: str, quotes: list[str]) -> list[dict[str, Any]]:
    spans = sorted(s for q in quotes if (s := _span(text, q)) is not None)
    out, pos = [], 0
    for a, b in spans:
        if a < pos:  # overlapping quotes: the first deletion covers it
            continue
        if a > pos:
            out.append({"text": text[pos:a], "del": False})
        out.append({"text": text[a:b], "del": True})
        pos = b
    if pos < len(text):
        out.append({"text": text[pos:], "del": False})
    return out


def _source_line(source: dict | None) -> str:
    if not source:
        return ""
    if source.get("kind") == "unread":
        pages = ", ".join(str(p) for p in source.get("pages_unread", []))
        return f"PDF page(s) {pages} had no readable text and were not reviewed."
    if source.get("kind") != "ocr":
        return "Text from an unrecognised source: check it against the original."
    pages = source.get("pages_ocr", [])
    return (
        f"Read from a scan by local OCR ({source.get('engine', 'Tesseract')}): "
        f"{len(pages)} {'page' if len(pages) == 1 else 'pages'}, average word confidence "
        f"{source.get('mean_conf', 0):.0f}%, {source.get('low_conf_share', 0):.0%} of words "
        "uncertain. Quotes follow the OCR text."
    )


def data_line(policy: dict[str, Any] | None) -> str:
    """Who saw the contract: the sensitivity label, where the model ran, and what was hidden."""
    if not policy:
        return ""
    label = str(policy.get("sensitivity", "")).capitalize()
    detected = str(policy.get("label_detected") or "")
    why = "; ".join(r[:1].lower() + r[1:] for r in policy.get("label_reasons") or [])
    if policy.get("label_set_by") == "auto":
        label += f" (suggested from the text: {why})" if why else " (suggested from the text)"
    elif (
        policy.get("label_set_by") == "person"
        and detected
        and detected != policy.get("sensitivity")
    ):
        reason = f" ({why})" if why else ""
        label = f"Detected: {detected.capitalize()}{reason}. Set to {label} by a person"
    if not policy.get("allowed", True):
        return f"{label}. Not sent to any model: {policy.get('reason', '')}"
    where = (
        "a model inside your network" if policy.get("location") == "local" else "an external model"
    )
    model = f" ({policy['model']})" if policy.get("model") else ""
    line = f"{label}. Reviewed by {where}{model}."
    if red := policy.get("redacted"):
        n = sum(red.values())
        line += (
            f" {n} {'identifier' if n == 1 else 'identifiers'} (names, contact details, account and"
            " ID numbers) were replaced by placeholders before sending."
        )
    if policy.get("sensitivity") == "restricted":
        line += " Restricted: a lawyer signs off every outcome."
    return line


def _counts(counts: dict[str, int] | None) -> str:
    if not counts:
        return "No score"
    return " · ".join(f"{counts.get(s, 0)} {s}" for s in ("critical", "major", "minor"))


def _meta(view: dict[str, Any], run_id: str | None) -> str:
    parts = [f"Run {run_id}"] if run_id else []
    if view.get("model"):
        parts.append(str(view["model"]))
    parts.append(f"Generated {_now()}")
    return " · ".join(parts)


def _route(view: dict[str, Any]) -> tuple[str, str]:
    route = view.get("route")
    if route in ROUTE_LABEL:
        return route, ROUTE_LABEL[route]
    return "none", "Not routed"


def redline_pdf(settings: Settings, view: dict[str, Any], run_id: str | None = None) -> bytes:
    contract = C.load_contract(settings.contract_dirs(), view["doc_id"])
    by_clause: dict[str, list[dict[str, Any]]] = {}
    for f in view["findings"]:
        by_clause.setdefault(f["clause_id"], []).append(f)
    route, route_label = _route(view)
    changed = len([c for c in contract.clauses if c.id in by_clause])
    n = len(view["findings"])
    data = {
        "title": contract.title or contract.doc_id,
        "title_lang": C.detect_lang(contract.title or ""),
        "doc_id": contract.doc_id,
        "route": route,
        "route_label": route_label,
        "meta": _meta(view, run_id),
        "source": _source_line(contract.source),
        "disclaimer": DISCLAIMER,
        "summary": (
            f"{n} {'change' if n == 1 else 'changes'} in {changed} "
            f"{'clause' if changed == 1 else 'clauses'}."
            if n
            else "No changes requested."
        ),
        "clauses": [
            {
                "id": c.id,
                "lang": c.lang,
                "segments": _segments(c.text, [f["quote"] for f in by_clause.get(c.id, [])]),
                "findings": [
                    {
                        "rule_id": f["rule_id"],
                        "severity": f["severity"],
                        "clause_type": f.get("clause_type", ""),
                        "issue": f["issue"],
                        "redline": f["redline"],
                        "redline_lang": C.detect_lang(f["redline"]),
                    }
                    for f in by_clause.get(c.id, [])
                ],
            }
            for c in contract.clauses
        ],
    }
    return _compile("redline.typ", data)


_MD_EMPHASIS = re.compile(r"\*\*|__|`")
_BULLET = re.compile(r"^\s*(?:[-*•]|\d+[.)])\s+")


def _memo_paragraphs(memo: str) -> list[dict[str, Any]]:
    """The agent's memo is light Markdown; render it as plain paragraphs and bullets."""
    out = []
    for line in memo.splitlines():
        line = line.strip()
        if not line:
            continue
        bullet = bool(_BULLET.match(line))
        text = _MD_EMPHASIS.sub("", _BULLET.sub("", line)).lstrip("#").strip()
        if text:
            out.append({"text": text, "lang": C.detect_lang(text), "bullet": bullet})
    return out


def _action(view: dict[str, Any]) -> str:
    decision = view.get("decision")
    if decision:
        who = decision.get("by") or "a person"
        text = f"{DECISION_LABEL.get(decision['decision'], decision['decision'])} ({who})."
        if decision.get("note"):
            text += f" Note: {decision['note']}"
        return text
    for a in view.get("actions", []):
        verb = "Sent to the counterparty" if a["kind"] == "counterparty" else "Escalated to legal"
        if a.get("dry_run"):
            verb = "Drafted, waiting for approval: " + verb.lower()
        return verb + "."
    if view.get("route") == "approve":
        return "Approved automatically; no outward action needed."
    if not view.get("route"):
        return "The agent did not finish; a lawyer must review the whole contract."
    return ""


def memo_pdf(settings: Settings, view: dict[str, Any], run_id: str) -> bytes:
    try:
        contract = C.load_contract(settings.contract_dirs(), view["doc_id"])
        title, source = contract.title or contract.doc_id, contract.source
    except FileNotFoundError:
        title, source = view["doc_id"], view.get("source")
    route, route_label = _route(view)
    data = {
        "title": title,
        "title_lang": C.detect_lang(title),
        "doc_id": view["doc_id"],
        "route": route,
        "route_label": route_label,
        "route_description": ROUTE_DESCRIPTION.get(
            route, "The review did not reach a route. A lawyer must review the contract."
        ),
        "risk": str(view["risk_score"]) if view.get("risk_score") is not None else "none",
        "counts": _counts(view.get("counts")),
        "reasons": list(view.get("reasons") or []),
        "action": _action(view),
        "source": _source_line(source),
        "data": data_line(view.get("data_policy")),
        "meta": _meta(view, run_id),
        "disclaimer": DISCLAIMER,
        "memo": _memo_paragraphs(view.get("memo") or ""),
        "findings": [
            {
                "clause_id": f["clause_id"],
                "rule_id": f["rule_id"],
                "severity": f["severity"],
                "quote": f["quote"],
                "quote_lang": C.detect_lang(f["quote"]),
                "issue": f["issue"],
                "redline": f["redline"],
                "redline_lang": C.detect_lang(f["redline"]),
            }
            for f in view["findings"]
        ],
        "flags": [
            {
                "clause_id": t["clause_id"],
                "rule_id": t["rule_id"],
                "status": t["status"],
                "tone": FLAG_TONE.get(t["status"], "plain"),
                "match": t["match"],
                "match_lang": C.detect_lang(t["match"]),
            }
            for t in view.get("tripwires") or []
        ],
    }
    return _compile("memo.typ", data)
