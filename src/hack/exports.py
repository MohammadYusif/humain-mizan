"""Word exports a legal team can use directly.

- redline.docx: the contract with real tracked changes (Word "Track Changes"): each offending quote
  is a deletion, the playbook wording is an insertion, and a comment explains the rule and issue.
  Arabic clauses are laid out right-to-left.
- memo.docx: the decision memo: route, reasons, red flags, findings, the human decision on record.
"""

from __future__ import annotations

import io
from datetime import UTC, datetime
from typing import Any

from docx import Document
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor

from .challenge import contracts as C
from .config import Settings

AUTHOR = "Mizan (AI review)"
DISCLAIMER = "Decision support generated by an AI agent; not legal advice. Review before use."


def _now() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


class _Ids:
    # Revision ids start high so they never coincide with comment ids (which count from 0).
    def __init__(self) -> None:
        self.n = 1000

    def next(self) -> str:
        self.n += 1
        return str(self.n)


def _rtl(paragraph) -> None:
    ppr = paragraph._p.get_or_add_pPr()
    ppr.append(OxmlElement("w:bidi"))


def _mark_run_rtl(run) -> None:
    run._r.get_or_add_rPr().append(OxmlElement("w:rtl"))


def _track(run, kind: str, ids: _Ids) -> None:
    """Wrap a run in <w:ins>/<w:del> so Word shows it as a tracked change."""
    wrapper = OxmlElement(f"w:{kind}")
    wrapper.set(qn("w:id"), ids.next())
    wrapper.set(qn("w:author"), AUTHOR)
    wrapper.set(qn("w:date"), _now())
    r = run._r
    if kind == "del":
        for t in r.findall(qn("w:t")):
            t.tag = qn("w:delText")
    r.addprevious(wrapper)
    wrapper.append(r)


def _span(clause_text: str, quote: str) -> tuple[int, int] | None:
    """Original-text span of a quote that was verified against the normalised clause."""
    norm, idx = C.normalize_with_map(clause_text)
    q = C.normalize(quote)
    at = norm.find(q) if q else -1
    if at < 0 or not idx:
        return None
    return idx[at], idx[at + len(q) - 1] + 1


def redline_docx(settings: Settings, view: dict[str, Any]) -> bytes:
    contract = C.load_contract(settings.contract_dirs(), view["doc_id"])
    by_clause: dict[str, list[dict[str, Any]]] = {}
    for f in view["findings"]:
        by_clause.setdefault(f["clause_id"], []).append(f)

    doc = Document()
    doc.styles["Normal"].font.name = "Arial"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(contract.title or contract.doc_id, level=1)
    note = doc.add_paragraph(
        f"Redline by {AUTHOR}. Route: {view['route'] or 'none'}. Changes are tracked: accept or "
        f"reject them in Word (Review → Track Changes). {DISCLAIMER}"
    )
    note.runs[0].font.size = Pt(9)
    note.runs[0].font.color.rgb = RGBColor(0x66, 0x66, 0x66)
    ids = _Ids()

    for clause in contract.clauses:
        p = doc.add_paragraph()
        if clause.lang == "ar":
            _rtl(p)
        findings = by_clause.get(clause.id, [])
        spans = sorted(
            (s, f) for f in findings if (s := _span(clause.text, f["quote"])) is not None
        )
        pos = 0
        for (a, b), _f in spans:
            if a < pos:  # overlapping quotes: the first deletion covers it
                continue
            if a > pos:
                run = p.add_run(clause.text[pos:a])
                if clause.lang == "ar":
                    _mark_run_rtl(run)
            deleted = p.add_run(clause.text[a:b])
            if clause.lang == "ar":
                _mark_run_rtl(deleted)
            _track(deleted, "del", ids)
            pos = b
        if pos < len(clause.text):
            run = p.add_run(clause.text[pos:])
            if clause.lang == "ar":
                _mark_run_rtl(run)
        for f in findings:
            ip = doc.add_paragraph()
            ins = ip.add_run(f["redline"])
            doc.add_comment(
                runs=ins,
                text=f"{f['rule_id']} ({f['severity']}): {f['issue']}",
                author=AUTHOR,
                initials="MZ",
            )
            _track(ins, "ins", ids)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def memo_docx(settings: Settings, view: dict[str, Any], run_id: str) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Arial"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(f"Contract review memo: {view['doc_id']}", level=1)
    meta = doc.add_paragraph(f"Run {run_id} · generated {_now()} · {DISCLAIMER}")
    meta.runs[0].font.size = Pt(9)

    doc.add_heading("Decision", level=2)
    route = view["route"] or "none (the agent did not finish; a lawyer must review)"
    doc.add_paragraph(
        f"Route: {route}. Risk score: {view['risk_score'] if view['risk_score'] is not None else '—'}."
    )
    for reason in view["reasons"]:
        doc.add_paragraph(reason, style="List Bullet")
    decision = view.get("decision")
    if decision:
        who = decision.get("by", "human")
        doc.add_paragraph(
            f"Action on record: {decision['decision']} by {who}."
            + (f" Note: {decision['note']}" if decision.get("note") else "")
        )

    if view.get("memo"):
        doc.add_heading("Agent's memo", level=2)
        for para in view["memo"].split("\n"):
            if para.strip():
                doc.add_paragraph(para.strip())

    doc.add_heading("Findings", level=2)
    if not view["findings"]:
        doc.add_paragraph("No playbook deviations recorded.")
    else:
        table = doc.add_table(rows=1, cols=5)
        table.style = "Light Grid Accent 1"
        for cell, h in zip(
            table.rows[0].cells,
            ("Clause", "Rule", "Severity", "Quote", "Proposed wording"),
            strict=True,
        ):
            cell.text = h
        for f in view["findings"]:
            row = table.add_row().cells
            for cell, v in zip(
                row,
                (f["clause_id"], f["rule_id"], f["severity"], f["quote"], f["redline"]),
                strict=True,
            ):
                cell.text = str(v)

    flags = view.get("tripwires") or []
    if flags:
        doc.add_heading("Deterministic red flags", level=2)
        for t in flags:
            doc.add_paragraph(
                f"{t['rule_id']} on {t['clause_id']} ({t['status']}): {t['match']}",
                style="List Bullet",
            )
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
